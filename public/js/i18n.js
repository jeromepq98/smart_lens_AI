export const LANGUAGE_NAMES = Object.freeze({ en: 'English', fil: 'Filipino', ceb: 'Cebuano' });
export const SUPPORTED = Object.freeze(['en', 'fil', 'ceb']);

let currentLanguage = 'en';
const listeners = new Set();

export function normalizeLanguage(value, fallback = 'en') {
  return SUPPORTED.includes(value) ? value : fallback;
}

export function getLanguage() {
  return currentLanguage;
}

export function setLanguage(language) {
  const next = normalizeLanguage(language);
  if (next === currentLanguage) return;
  currentLanguage = next;
  document.documentElement.lang = next === 'fil' ? 'fil' : next === 'ceb' ? 'ceb' : 'en';
  for (const listener of listeners) listener(next);
}

export function onLanguageChange(listener) {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

export function t(key, vars = {}) {
  const dictionary = DICTIONARIES[currentLanguage] || DICTIONARIES.en;
  let value = dictionary[key] ?? DICTIONARIES.en[key] ?? key;
  for (const [name, replacement] of Object.entries(vars)) {
    value = value.replaceAll(`{${name}}`, String(replacement));
  }
  return value;
}

export function languageDisplayName(language) {
  return LANGUAGE_NAMES[normalizeLanguage(language)] || 'English';
}
